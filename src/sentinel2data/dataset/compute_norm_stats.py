"""Per-band mean/std over the TRAINING split only -> frozen, no val/test leakage.

Run once after the dataset is built (splits are zone-disjoint, so train stats never
see val/test pixels). Emits a LightningCLI-mergeable YAML holding ``data.norm_mean`` /
``data.norm_std`` -- the FULL per-band stack in 1-based order. The loaders z-score every
train patch and every stitched val/test/predict window with these frozen stats (sliced
to the selected ``bands``) instead of per-image stats -- see
:func:`sentinel2data.dataset.apply_norm`.

Driven by the dataset CLI:

    python -m sentinel2data.cli norm-stats --dataset-dir <root> --out src/unet/configs/norm_stats.yaml

then merge over the base config:

    python -m unet.cli fit --config src/unet/configs/unet.yaml --config src/unet/configs/norm_stats.yaml

Band count is read from the imagery (20-band S2 or 23-band S2-V2); names come from
:data:`S2_V2_BANDS`. nodata: a COG's declared nodata is honoured, else (``exclude_zero``)
0 is dropped. SAR bands (VV/VH ascending+descending) can be clipped before stats so
speckle outliers don't inflate std: ``--sar-clip LO HI`` (raw stored units; off by default).
"""
from pathlib import Path

import numpy as np
import rasterio

from sentinel2data.dataset.bands import S2_V2_BANDS
from sentinel2data.dataset.datasets import _read_split_csv

IMAGERY_COLS = ("image_path", "tile_path")  # split-CSV column holding the imagery COG
SAR_NAMES = {"VV_ascending", "VH_ascending", "VV_descending", "VH_descending"}


def _band_names(n):
    """Names for an ``n``-band stack (S2_V2_BANDS prefix; generic pad beyond 23)."""
    names = list(S2_V2_BANDS[:n])
    names += [f"band{i + 1}" for i in range(len(names), n)]
    return names


def _train_imagery_paths(dataset_dir):
    """Unique imagery COG paths in the train split (dedup the per-patch rows)."""
    df = _read_split_csv(dataset_dir, "train")
    col = next((c for c in IMAGERY_COLS if c in df.columns), None)
    if col is None:
        raise ValueError(
            f"train.csv has no imagery column {IMAGERY_COLS}; got {list(df.columns)}"
        )
    return df[col].drop_duplicates().tolist()


def compute(dataset_dir, exclude_zero=True, sar_clip=None):
    """Streaming per-band ``(names, mean, std)`` over the train-split COGs (float32)."""
    root = Path(dataset_dir)
    rel_paths = _train_imagery_paths(root)
    if not rel_paths:
        raise ValueError(f"No training imagery found under {root}/splits/train.csv")

    with rasterio.open(root / rel_paths[0]) as src0:
        n = src0.count
    names = _band_names(n)
    sar_idx = {i for i, nm in enumerate(names) if nm in SAR_NAMES}

    s = np.zeros(n, "float64")
    ss = np.zeros(n, "float64")
    cnt = np.zeros(n, "float64")

    for rel in rel_paths:
        path = root / rel
        if not path.exists():
            print(f"[stats] skip {rel}: not found")
            continue
        with rasterio.open(path) as src:
            arr = src.read().astype("float64")  # (C, H, W)
            nodata = src.nodata
        if arr.shape[0] != n:
            raise ValueError(f"{path}: {arr.shape[0]} bands, expected {n}")
        for b in range(n):
            band = arr[b]
            valid = np.isfinite(band)
            if nodata is not None:
                valid &= band != nodata
            elif exclude_zero:
                valid &= band != 0
            v = band[valid]
            if sar_clip and b in sar_idx:
                v = np.clip(v, sar_clip[0], sar_clip[1])
            s[b] += v.sum()
            ss[b] += (v * v).sum()
            cnt[b] += v.size
        print(f"[stats] accumulated {Path(rel).stem}")

    cnt[cnt == 0] = 1.0
    mean = s / cnt
    std = np.sqrt(np.maximum(ss / cnt - mean ** 2, 0.0))
    return names, mean.astype("float32"), std.astype("float32")


def _yaml_list(vals):
    return "[" + ", ".join(f"{float(x):.6g}" for x in vals) + "]"


def write_stats_yaml(out_path, mean, std):
    """Write a LightningCLI-mergeable ``data.norm_mean`` / ``data.norm_std`` config."""
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "# Frozen per-band train-set normalisation stats (full stack, 1-based order).\n"
        "# Generated by `sentinel2data norm-stats`. Merge over the base config:\n"
        f"#   python -m unet.cli fit --config src/unet/configs/unet.yaml --config {out.as_posix()}\n"
        "data:\n"
        f"  norm_mean: {_yaml_list(mean)}\n"
        f"  norm_std: {_yaml_list(std)}\n"
    )
    return out


def print_table(names, mean, std):
    for nm, m, sd in zip(names, mean, std):
        print(f"  {nm:>14}: mean={m:12.3f}  std={sd:12.3f}")
