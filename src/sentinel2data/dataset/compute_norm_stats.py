"""Per-band mean/std over the TRAINING split only -> frozen
Run cli tool after the dataset is built to obtain norm_stats.yaml.

    python -m sentinel2data.cli norm-stats --dataset-dir <root> --out src/unet/configs/norm_stats.yaml

then merge over the base config:
    python -m unet.cli fit --config src/unet/configs/unet.yaml --config src/unet/configs/norm_stats.yaml

``--splits`` widens the source set for the train+val refit protocol, whose fit
draws from train AND val while the default stats saw train only:

    python -m sentinel2data.cli norm-stats --dataset-dir <root> \\
        --splits train --splits val --out <root>/norm_stats_tv.yaml

TEST IS NEVER A VALID SPLIT HERE and the function refuses it: stats computed
over the report set leak it into every input the model sees. Whichever
convention is chosen (train-only or train+val) must be held constant across
every arm inside a comparison.
"""
from pathlib import Path
import numpy as np
import rasterio
from sentinel2data.dataset.bands import S2_V2_BANDS
from sentinel2data.dataset.datasets import _read_split_csv

IMAGERY_COLS = ("image_path", "tile_path")  # split-CSV column holding the imagery COG
SAR_NAMES = {"VV_ascending", "VH_ascending", "VV_descending", "VH_descending"}


def _band_names(n):
    """Names for an ``n``-band stack (S2_V2_BANDS prefix; generic pad beyond 23)."""
    names = list(S2_V2_BANDS[:n])
    names += [f"band{i + 1}" for i in range(len(names), n)]
    return names


def _train_imagery_paths(dataset_dir, splits=("train",)):
    """Unique imagery COG paths across ``splits`` (dedup the per-patch rows)."""
    splits = tuple(str(s) for s in (splits or ("train",)))
    if "test" in splits:
        raise ValueError(
            "norm stats must never be computed over 'test' — that is the "
            f"held-out report split. Got splits={splits!r}."
        )
    paths = []
    for split in splits:
        df = _read_split_csv(dataset_dir, split)
        col = next((c for c in IMAGERY_COLS if c in df.columns), None)
        if col is None:
            raise ValueError(
                f"{split}.csv has no imagery column {IMAGERY_COLS}; "
                f"got {list(df.columns)}"
            )
        paths.extend(df[col].drop_duplicates().tolist())
    # Dedup ACROSS splits too — a tile listed twice would be double-weighted.
    return list(dict.fromkeys(paths))


def compute(dataset_dir, exclude_zero=True, sar_clip=None, splits=("train",)):
    """Streaming per-band ``(names, mean, std)`` over the split COGs (float32)."""
    root = Path(dataset_dir)
    splits = tuple(str(s) for s in (splits or ("train",)))
    rel_paths = _train_imagery_paths(root, splits)
    if not rel_paths:
        raise ValueError(
            f"No imagery found under {root}/splits/ for splits={splits!r}")
    print(f"[stats] {len(rel_paths)} unique tiles over splits {splits}")

    with rasterio.open(root / rel_paths[0]) as src0:
        n = src0.count
    names = _band_names(n)
    sar_idx = {i for i, nm in enumerate(names) if nm in SAR_NAMES}

    s = np.zeros(n, "float64")
    ss = np.zeros(n, "float64")
    cnt = np.zeros(n, "float64")

    for rel in rel_paths:
        path = root / rel
        if not path.exists():
            print(f"[stats] skip {rel}: not found")
            continue
        with rasterio.open(path) as src:
            arr = src.read().astype("float64")  # (C, H, W)
            nodata = src.nodata
        if arr.shape[0] != n:
            raise ValueError(f"{path}: {arr.shape[0]} bands, expected {n}")
        for b in range(n):
            band = arr[b]
            valid = np.isfinite(band)
            if nodata is not None:
                valid &= band != nodata
            elif exclude_zero:
                valid &= band != 0
            v = band[valid]
            if sar_clip and b in sar_idx:
                v = np.clip(v, sar_clip[0], sar_clip[1])
            s[b] += v.sum()
            ss[b] += (v * v).sum()
            cnt[b] += v.size
        # print(f"[stats] accumulated {Path(rel).stem}")

    cnt[cnt == 0] = 1.0
    mean = s / cnt
    std = np.sqrt(np.maximum(ss / cnt - mean ** 2, 0.0))
    return names, mean.astype("float32"), std.astype("float32")


def _yaml_list(vals):
    return "[" + ", ".join(f"{float(x):.6g}" for x in vals) + "]"


def write_stats_yaml(out_path, mean, std, splits=("train",)):
    """Write a LightningCLI-mergeable ``data.norm_mean`` / ``data.norm_std`` config."""
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    src = "+".join(str(s) for s in (splits or ("train",)))
    out.write_text(
        f"# Frozen per-band normalisation stats over the {src.upper()} split(s)\n"
        "# (full stack, 1-based order).\n"
        "# Generated by `sentinel2data norm-stats`. Merge over the base config:\n"
        f"#   python -m unet.cli fit --config src/unet/configs/unet.yaml --config {out.as_posix()}\n"
        f"# splits: {src}   <- hold this convention CONSTANT across every arm\n"
        "#            inside a comparison; test never contributes.\n"
        "data:\n"
        f"  norm_mean: {_yaml_list(mean)}\n"
        f"  norm_std: {_yaml_list(std)}\n"
    )
    return out


def print_table(names, mean, std):
    for nm, m, sd in zip(names, mean, std):
        print(f"  {nm:>14}: mean={m:12.3f}  std={sd:12.3f}")
